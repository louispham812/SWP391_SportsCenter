export const DEFAULT_SPORT_IMG = 'https://images.unsplash.com/photo-1517649763962-0c623266ddc0?auto=format&fit=crop&w=800&q=80';
export const DEFAULT_FACILITY_IMG = 'https://images.unsplash.com/photo-1534438327276-14e5300c3a48?auto=format&fit=crop&w=800&q=80';

export function getSportMedia(slug) {
  if (!slug) return { image: DEFAULT_SPORT_IMG, banner: DEFAULT_SPORT_IMG, category: 'Thể Thao', features: [] };
  const cleanSlug = slug.toLowerCase().trim();
  if (SPORT_MEDIA_MAP[cleanSlug]) {
    return SPORT_MEDIA_MAP[cleanSlug];
  }

  // Keyword-based fallback for sports
  if (cleanSlug.includes('pickleball')) {
    return SPORT_MEDIA_MAP['pickleball'];
  }
  if (cleanSlug.includes('tennis')) {
    return SPORT_MEDIA_MAP['tennis'];
  }
  if (cleanSlug.includes('badminton') || cleanSlug.includes('cau-long')) {
    return SPORT_MEDIA_MAP['badminton'];
  }
  if (cleanSlug.includes('football') || cleanSlug.includes('soccer') || cleanSlug.includes('bong-da')) {
    return SPORT_MEDIA_MAP['football'];
  }
  if (cleanSlug.includes('volleyball') || cleanSlug.includes('bong-chuyen')) {
    return SPORT_MEDIA_MAP['volleyball'];
  }
  if (cleanSlug.includes('table-tennis') || cleanSlug.includes('ping-pong') || cleanSlug.includes('bong-ban')) {
    return SPORT_MEDIA_MAP['table-tennis'];
  }
  if (cleanSlug.includes('swimming') || cleanSlug.includes('pool') || cleanSlug.includes('boi')) {
    return SPORT_MEDIA_MAP['swimming'];
  }
  if (cleanSlug.includes('athletics') || cleanSlug.includes('run') || cleanSlug.includes('dien-kinh')) {
    return SPORT_MEDIA_MAP['athletics'];
  }
  if (cleanSlug.includes('yoga') || cleanSlug.includes('pilates')) {
    return SPORT_MEDIA_MAP['yoga-pilates'];
  }
  if (cleanSlug.includes('gym') || cleanSlug.includes('fitness')) {
    return SPORT_MEDIA_MAP['gym-fitness'];
  }

  return {
    image: DEFAULT_SPORT_IMG,
    banner: DEFAULT_SPORT_IMG,
    category: 'Thể Thao Đỉnh Cao',
    features: ['Tiêu chuẩn chất lượng', 'Trang thiết bị hiện đại'],
  };
}

